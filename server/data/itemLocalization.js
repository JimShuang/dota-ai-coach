function getDisplayName(internalName) {
  if (!internalName) return '—';
  return ITEM_NAMES_ZH[internalName]
    || internalName.replace('item_', '').replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

